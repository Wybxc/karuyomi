import { readFile, writeFile } from 'node:fs/promises';
import protocol from '../packages/contracts/protocol.json' with { type: 'json' };

const root = new URL('../', import.meta.url);
const warning = '// Generated by scripts/generate-protocol.ts. Do not edit.\n';
const outputs = {
  'packages/contracts/src/generated.ts':
    warning +
    Object.entries(protocol)
      .map(
        ([key, value]) =>
          `export const ${key} = ${JSON.stringify(value)} as const;\n`,
      )
      .join(''),
  'packages/source_runtime/lib/src/generated.dart':
    warning +
    Object.entries(protocol)
      .map(([key, value]) => {
        const literal =
          typeof value === 'string'
            ? `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`
            : JSON.stringify(value);
        return `const ${key} = ${literal};\n`;
      })
      .join(''),
};
for (const [path, content] of Object.entries(outputs)) {
  const url = new URL(path, root);
  if (process.argv.includes('--check')) {
    if ((await readFile(url, 'utf8')) !== content) {
      throw new Error(`${path} is stale; run pnpm generate`);
    }
  } else {
    await writeFile(url, content);
  }
}
