package org.teavm.classlib.java.util.regex;

/**
 * Unicode category scope (i.e IsL, IsM, ...)
 * @author Nikolay A. Kuznetsov
 */
class PatchedUnicodeCategoryScope extends TUnicodeCategory {

    public PatchedUnicodeCategoryScope(int category) {
        // General category C includes unassigned and control characters.
        super(category == 0xF0000 ? 0xD8001 : category);
    }

    @Override
    public boolean contains(int ch) {
        return alt ^ ((category >> Character.getType(ch)) & 1) != 0;
    }
}
