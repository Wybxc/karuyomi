import { readFile, writeFile, mkdtemp, rm } from 'node:fs/promises';
import path from 'node:path';
import { tmpdir } from 'node:os';
import protocol from '../../packages/contracts/protocol.json' with { type: 'json' };
import { readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { execa } from 'execa';
import { dartExecutable } from './dart-plugin.ts';

const ROOT = fileURLToPath(new URL('../../', import.meta.url));

const generatedDirectories = [
  'packages/protocol/src',
  'packages/source_runtime/lib/src/pb',
];
const warning = '// Generated by scripts/generate-protocol.ts. Do not edit.\n';

const run = execa({
  cwd: ROOT,
  stdin: 'ignore',
  stdout: 'inherit',
  stderr: 'inherit',
  buffer: false,
  shell: false,
  preferLocal: false,
  verbose: 'none',
});

export async function main(args: string[]): Promise<void> {
  if (args.length === 1 && args[0] === '--setup') {
    await run(dartExecutable(), [
      'pub',
      'get',
      '--directory',
      'tools/protocol/generator',
      '--enforce-lockfile',
    ]);
    return;
  }
  if (args.length > 1 || (args.length === 1 && args[0] !== '--check'))
    throw new Error('Usage: generate-protocol.ts [--check|--setup]');
  const check = args[0] === '--check';
  await run('pnpm', ['exec', 'buf', 'format', '--diff', '--exit-code']);
  await run('pnpm', ['exec', 'buf', 'lint']);
  await run('pnpm', ['exec', 'buf', 'build']);
  const output = check
    ? await mkdtemp(path.join(tmpdir(), 'karuyomi-protocol-'))
    : ROOT;
  try {
    await run('pnpm', ['exec', 'buf', 'generate', '--output', output]);
    if (check) {
      for (const directory of generatedDirectories) {
        const actualDirectory = path.join(ROOT, directory);
        const expectedDirectory = path.join(output, directory);
        const actualFiles = readdirSync(actualDirectory, {
          recursive: true,
          withFileTypes: true,
        })
          .filter((entry) => entry.isFile())
          .map((entry) =>
            path.relative(
              actualDirectory,
              path.join(entry.parentPath, entry.name),
            ),
          )
          .sort();
        const expectedFiles = readdirSync(expectedDirectory, {
          recursive: true,
          withFileTypes: true,
        })
          .filter((entry) => entry.isFile())
          .map((entry) =>
            path.relative(
              expectedDirectory,
              path.join(entry.parentPath, entry.name),
            ),
          )
          .sort();
        if (JSON.stringify(actualFiles) !== JSON.stringify(expectedFiles))
          throw new Error(
            `${directory} generated file set is stale; run pnpm generate`,
          );
        for (const file of expectedFiles) {
          const [actual, expected] = await Promise.all([
            readFile(path.join(actualDirectory, file)),
            readFile(path.join(expectedDirectory, file)),
          ]);
          if (!actual.equals(expected))
            throw new Error(`${directory}/${file} is stale; run pnpm generate`);
        }
      }
    }
    const constants = {
      'packages/contracts/src/generated.ts':
        warning +
        Object.entries(protocol)
          .map(
            ([key, value]) =>
              `export const ${key} = ${JSON.stringify(value)} as const;\n`,
          )
          .join(''),
      'packages/source_runtime/lib/src/generated.dart':
        warning +
        Object.entries(protocol)
          .map(([key, value]) => {
            const literal =
              typeof value === 'string'
                ? `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`
                : JSON.stringify(value);
            return `const ${key} = ${literal};\n`;
          })
          .join(''),
    };
    for (const [file, content] of Object.entries(constants)) {
      if (check) {
        if ((await readFile(path.join(ROOT, file), 'utf8')) !== content)
          throw new Error(`${file} is stale; run pnpm generate`);
      } else await writeFile(path.join(ROOT, file), content);
    }
    await run('pnpm', ['--filter', '@karuyomi/protocol', 'build']);
  } finally {
    if (check) await rm(output, { recursive: true, force: true });
  }
}
